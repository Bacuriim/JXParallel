"""Generates the FXML load benchmark screens: N form screens with their own controllers.

Output (checked in, rerun only to change the shape):
  jxparallel-examples/src/main/resources/fxmlbench/screenNN.fxml
  jxparallel-examples/src/main/java/com/jxparallel/examples/fxmlbench/ScreenNNController.java
and the same screens in JXML for the JXForge benchmark (jxparallel-examples-native):
  src/main/jxml/forgebench/screenNN.jxml
  src/main/java/com/jxparallel/examples/nativeui/forgebench/ScreenNNController.java
"""
from pathlib import Path

SCREENS = 20
TABS = 3
ROWS_PER_TAB = 15
BUTTONS = 8
INJECTED_FIELDS = 12  # first form controls injected with @FXML, on top of the buttons

root = Path(__file__).resolve().parent.parent / "jxparallel-examples" / "src" / "main"
fxml_dir = root / "resources" / "fxmlbench"
java_dir = root / "java" / "com" / "jxparallel" / "examples" / "fxmlbench"
fxml_dir.mkdir(parents=True, exist_ok=True)
java_dir.mkdir(parents=True, exist_ok=True)

CONTROLS = [
    ("TextField", 'promptText="Value {n}"'),
    ("ComboBox", 'promptText="Choose {n}"'),
    ("CheckBox", 'text="Enabled {n}"'),
    ("DatePicker", 'promptText="Date {n}"'),
    ("Spinner", 'min="0" max="100" initialValue="{n}"'),
]

for s in range(1, SCREENS + 1):
    name = f"Screen{s:02d}Controller"
    field_types = []
    rows = []
    n = 0
    tabs = []
    for t in range(TABS):
        grid = []
        for r in range(ROWS_PER_TAB):
            kind, attrs = CONTROLS[n % len(CONTROLS)]
            fx_id = f' fx:id="field{n}"' if n < INJECTED_FIELDS else ""
            if n < INJECTED_FIELDS:
                field_types.append((kind, f"field{n}"))
            grid.append(f'                <Label text="Field {s}.{n}" GridPane.rowIndex="{r}" GridPane.columnIndex="0"/>')
            grid.append(f'                <{kind}{fx_id} {attrs.format(n=n)} GridPane.rowIndex="{r}" GridPane.columnIndex="1"/>')
            n += 1
        tabs.append(f'''        <Tab text="Section {t + 1}" closable="false">
          <ScrollPane fitToWidth="true">
            <GridPane hgap="8" vgap="6">
{chr(10).join(grid)}
            </GridPane>
          </ScrollPane>
        </Tab>''')
    buttons = "\n".join(
        f'      <Button fx:id="button{b}" text="Action {b}" onAction="#onAction"/>' for b in range(BUTTONS))
    (fxml_dir / f"screen{s:02d}.fxml").write_text(f'''<?xml version="1.0" encoding="UTF-8"?>
<?import javafx.scene.control.*?>
<?import javafx.scene.layout.*?>
<BorderPane xmlns="http://javafx.com/javafx" xmlns:fx="http://javafx.com/fxml"
            fx:controller="com.jxparallel.examples.fxmlbench.{name}">
  <top>
    <ToolBar>
{buttons}
    </ToolBar>
  </top>
  <center>
    <TabPane>
{chr(10).join(tabs)}
    </TabPane>
  </center>
  <bottom>
    <HBox spacing="12">
      <Label fx:id="status" text="Ready"/>
      <Label text="Screen {s}"/>
      <Label text="User"/>
      <Label text="v1.0"/>
    </HBox>
  </bottom>
</BorderPane>
''', encoding="utf-8")

    imports = sorted({"Button", "Label"} | {k for k, _ in field_types})
    fields = "\n".join(f"    @FXML private Button button{b};" for b in range(BUTTONS))
    fields += "\n    @FXML private Label status;\n"
    fields += "\n".join(f"    @FXML private {k}{'<String>' if k == 'ComboBox' else '<Integer>' if k == 'Spinner' else ''} {f};"
                        for k, f in field_types)
    combos = [f for k, f in field_types if k == "ComboBox"]
    init = "\n".join(f'        {f}.getItems().addAll("A", "B", "C", "D");' for f in combos)
    (java_dir / f"{name}.java").write_text(f'''package com.jxparallel.examples.fxmlbench;

{chr(10).join(f"import javafx.scene.control.{i};" for i in imports)}
import javafx.event.ActionEvent;
import javafx.fxml.FXML;

/** Generated by scripts/generate-fxml-bench.py. */
public class {name} {{
{fields}

    @FXML
    private void initialize() {{
{init}
        status.setText("Loaded");
    }}

    @FXML
    private void onAction(ActionEvent event) {{
        status.setText(((Button) event.getSource()).getText());
    }}
}}
''', encoding="utf-8")

print(f"{SCREENS} screens written to {fxml_dir} and {java_dir}")

# ---- the same screens in JXML (JXForge benchmark) ---------------------------------------------
# Same layout, texts and controls. The controls FXML injects with fx:id are bound to controller
# getters here, the buttons call a controller method, and the status label shows the controller's
# text ("Loaded", which the FXML controller's initialize() sets).
native_root = Path(__file__).resolve().parent.parent / "jxparallel-examples-native" / "src" / "main"
jxml_dir = native_root / "jxml" / "forgebench"
jx_java_dir = native_root / "java" / "com" / "jxparallel" / "examples" / "nativeui" / "forgebench"
jxml_dir.mkdir(parents=True, exist_ok=True)
jx_java_dir.mkdir(parents=True, exist_ok=True)

JX_CONTROLS = [  # tag, attributes, bound attribute, getter type, getter value
    ("TextField", 'prompt="Value {n}"', "text", "String", '""'),
    ("ComboBox", 'prompt="Choose {n}"', "value", "String", '""'),
    ("CheckBox", 'text="Enabled {n}"', "selected", "boolean", "false"),
    ("DatePicker", 'prompt="Date {n}"', "value", "String", '""'),
    ("Spinner", 'min="0" max="100" value="{n}"', "value", "String", '"{n}"'),
]

for s in range(1, SCREENS + 1):
    name = f"Screen{s:02d}Controller"
    getters = []
    n = 0
    tabs = []
    for t in range(TABS):
        grid = []
        for r in range(ROWS_PER_TAB):
            kind, attrs, bound, jtype, jvalue = JX_CONTROLS[n % len(JX_CONTROLS)]
            attrs = attrs.format(n=n)
            if n < INJECTED_FIELDS:
                if kind == "Spinner":
                    attrs = 'min="0" max="100"'
                if kind == "ComboBox":
                    attrs += ' items="${choices}"'
                attrs += f' {bound}="${{field{n}}}"'
                getters.append((jtype, f"Field{n}", jvalue.format(n=n)))
            grid.append(f'          <Label text="Field {s}.{n}" row="{r}" column="0"/>')
            grid.append(f'          <{kind} {attrs} row="{r}" column="1"/>')
            n += 1
        tabs.append(f'''    <Tab title="Section {t + 1}" closable="false">
      <Scroll fitToWidth="true">
        <Grid hgap="8" vgap="6">
{chr(10).join(grid)}
        </Grid>
      </Scroll>
    </Tab>''')
    buttons = "\n".join(f'    <Button text="Action {b}" onAction="#onAction"/>' for b in range(BUTTONS))
    (jxml_dir / f"screen{s:02d}.jxml").write_text(f'''<?xml version="1.0" encoding="UTF-8"?>
<Border controller="com.jxparallel.examples.nativeui.forgebench.{name}">
  <Row slot="top" gap="4" padding="4 8">
{buttons}
  </Row>
  <Tabs slot="center">
{chr(10).join(tabs)}
  </Tabs>
  <Row slot="bottom" gap="12">
    <Label text="${{status}}"/>
    <Label text="Screen {s}"/>
    <Label text="User"/>
    <Label text="v1.0"/>
  </Row>
</Border>
''', encoding="utf-8")

    methods = "\n\n".join(f"    public {t} get{f}() {{\n        return {v};\n    }}" for t, f, v in getters)
    (jx_java_dir / f"{name}.java").write_text(f'''package com.jxparallel.examples.nativeui.forgebench;

import java.util.Arrays;
import java.util.List;

/** Generated by scripts/generate-fxml-bench.py: the controller of forgebench/screen{s:02d}.jxml. */
public class {name} {{
    private static final List<String> CHOICES = Arrays.asList("A", "B", "C", "D");
    private String status = "Loaded";

    public String getStatus() {{
        return status;
    }}

    public List<String> getChoices() {{
        return CHOICES;
    }}

{methods}

    public void onAction() {{
        status = "Action";
    }}
}}
''', encoding="utf-8")

print(f"{SCREENS} JXML screens written to {jxml_dir} and {jx_java_dir}")
